function CommandItem({
  className,
  children,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Item>) {
  return (
    <CommandPrimitive.Item
      data-slot="command-item"
      className={cn(
        "group/command-item relative isolate flex transition-colors duration-(--dur-1) min-h-10 cursor-default items-center gap-3 rounded-sm px-2 py-1.5 text-sm outline-hidden select-none in-data-[slot=dialog-content]:rounded-lg! data-[disabled=true]:pointer-events-none data-[disabled=true]:opacity-50 data-selected:text-foreground",
        // The highlight is a pseudo-element so it can glide between rows (see CommandList).
        "before:absolute before:inset-0 before:-z-10 before:rounded-[inherit] before:bg-accent before:opacity-0 data-selected:before:opacity-100 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 data-selected:*:[svg]:text-foreground [&>svg:first-child:not([class*='size-'])]:box-content [&>svg:first-child:not([class*='size-'])]:size-4 [&>svg:first-child:not([class*='size-'])]:rounded-md [&>svg:first-child:not([class*='size-'])]:border [&>svg:first-child:not([class*='size-'])]:bg-sunken [&>svg:first-child:not([class*='size-'])]:p-1.5 data-selected:[&>svg:first-child:not([class*='size-'])]:bg-card",
        className
      )}
      {...props}
    >
      {children}
      <CheckIcon className="ml-auto opacity-0 group-has-data-[slot=command-shortcut]/command-item:hidden group-data-[checked=true]/command-item:opacity-100" />
    </CommandPrimitive.Item>
  )
}

